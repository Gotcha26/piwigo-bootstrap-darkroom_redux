import contextlib
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path

TOOLS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(TOOLS))

import vendor  # noqa: E402


def credited(**overrides):
    base = {"version": "1.0.0", "source": "npm", "license": "MIT", "files": ["dist/a.js"],
            "name": "Alpha", "url": "https://alpha.example", "author": "Ann"}
    base.update(overrides)
    return base


MANIFEST = {
    "components": {
        "alpha": credited(),
        "beta": credited(name="Beta", license="Apache-2.0", fork=True, version="2.0"),
        "hidden": credited(name="Hidden", credit=False),
    },
    "credits_extra": [
        {"name": "Upstream", "url": "https://up.example", "author": "O'Reilly", "license": "Apache 2.0"},
        {"name": "Fonts", "version": "5.3.0", "url": "https://f.example", "author": "F", "license": "SIL OFL 1.1"},
    ],
}


class CreditEntriesTest(unittest.TestCase):
    def test_components_then_extras_in_manifest_order(self):
        names = [entry["name"] for entry in vendor.credit_entries(MANIFEST)]
        self.assertEqual(names, ["Alpha 1.0.0", "Beta 2.0 (fork)", "Upstream", "Fonts 5.3.0"])

    def test_component_without_credit_metadata_is_refused(self):
        manifest = {"components": {"x": credited(url=None)}}
        with self.assertRaises(vendor.ManifestError):
            vendor.credit_entries(manifest)

    def test_markup_in_a_field_is_refused(self):
        # The shared credits template prints the fields without escaping.
        manifest = {"components": {"x": credited(author="A & B")}}
        with self.assertRaises(vendor.ManifestError):
            vendor.credit_entries(manifest)


GROUPED = dict(MANIFEST, credits_groups=[
    {"id": "core", "items": ["Upstream", "beta"]},
    {"id": "fonts", "items": ["Fonts", "alpha"]},
])


class CreditGroupsTest(unittest.TestCase):
    def test_no_family_declared_gives_none(self):
        self.assertIsNone(vendor.credit_groups(MANIFEST))

    def test_families_in_declared_order_with_declared_items(self):
        groups = vendor.credit_groups(GROUPED)
        self.assertEqual([gid for gid, _ in groups], ["core", "fonts"])
        self.assertEqual([e["name"] for e in groups[0][1]], ["Upstream", "Beta 2.0 (fork)"])
        self.assertEqual([e["name"] for e in groups[1][1]], ["Fonts 5.3.0", "Alpha 1.0.0"])

    def test_an_entry_left_out_of_every_family_is_refused(self):
        manifest = dict(MANIFEST, credits_groups=[{"id": "core", "items": ["alpha", "beta", "Upstream"]}])
        with self.assertRaisesRegex(vendor.ManifestError, "no family for 'Fonts'"):
            vendor.credit_groups(manifest)

    def test_an_entry_in_two_families_is_refused(self):
        manifest = dict(MANIFEST, credits_groups=[
            {"id": "a", "items": ["alpha", "beta", "Upstream", "Fonts"]}, {"id": "b", "items": ["alpha"]}])
        with self.assertRaisesRegex(vendor.ManifestError, "both"):
            vendor.credit_groups(manifest)

    def test_an_unknown_or_uncredited_reference_is_refused(self):
        for ref in ("nope", "hidden"):
            manifest = dict(MANIFEST, credits_groups=[
                {"id": "a", "items": ["alpha", "beta", "Upstream", "Fonts", ref]}])
            with self.assertRaises(vendor.ManifestError):
                vendor.credit_groups(manifest)

    def test_a_family_id_must_be_a_plain_identifier(self):
        manifest = dict(MANIFEST, credits_groups=[{"id": "Core!", "items": ["alpha", "beta", "Upstream", "Fonts"]}])
        with self.assertRaises(vendor.ManifestError):
            vendor.credit_groups(manifest)

    def test_render_keys_the_lists_by_family(self):
        text = vendor.render_credits(GROUPED)
        self.assertIn("  'core' => array(\n    array('name' => 'Upstream'", text)
        self.assertIn("  'fonts' => array(\n    array('name' => 'Fonts 5.3.0'", text)
        self.assertLess(text.index("'core'"), text.index("'fonts'"))
        self.assertNotIn("Hidden", text)


class RenderCreditsTest(unittest.TestCase):
    def test_render_lists_every_name_and_license(self):
        text = vendor.render_credits(MANIFEST)
        for needle in ("'Alpha 1.0.0'", "'Beta 2.0 (fork)'", "'Upstream'", "'Fonts 5.3.0'",
                       "'MIT'", "'Apache-2.0'", "'Apache 2.0'", "'SIL OFL 1.1'"):
            self.assertIn(needle, text)
        self.assertNotIn("Hidden", text)

    def test_render_escapes_apostrophes(self):
        self.assertIn("'O\\'Reilly'", vendor.render_credits(MANIFEST))

    def test_render_is_a_guarded_generated_php_file(self):
        text = vendor.render_credits(MANIFEST)
        self.assertTrue(text.startswith("<?php\n"))
        self.assertIn("defined('PHPWG_ROOT_PATH') or die(", text)
        self.assertIn("generated by tools/vendor.py credits", text)
        self.assertIn("do not edit", text)
        self.assertIn("return array(", text)


class CreditsCommandTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        (self.root / "include").mkdir()
        self.manifest = self.root / "vendor.json"
        self.manifest.write_text(json.dumps(MANIFEST), encoding="utf-8")
        self.target = self.root / "include" / "credits.php"

    def run_main(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
            code = vendor.main(list(argv) + ["--root", str(self.root), "--manifest", str(self.manifest)],
                               tracked=lambda root: {"node_modules/%s/dist/a.js" % name
                                                     for name in MANIFEST["components"]})
        return code, out.getvalue()

    def test_dry_run_writes_nothing(self):
        code, out = self.run_main("credits")
        self.assertEqual(code, 0)
        self.assertFalse(self.target.exists())
        self.assertIn("Dry run", out)

    def test_apply_writes_the_rendered_file(self):
        code, _ = self.run_main("credits", "--apply")
        self.assertEqual(code, 0)
        self.assertEqual(self.target.read_text(encoding="utf-8"), vendor.render_credits(MANIFEST))

    def test_check_reports_a_stale_credits_file(self):
        self.target.write_text("<?php return array();\n", encoding="utf-8")
        code, out = self.run_main("check")
        self.assertEqual(code, 1)
        self.assertIn("credits.php", out)

    def test_check_reports_a_missing_credits_file(self):
        code, out = self.run_main("check")
        self.assertEqual(code, 1)
        self.assertIn("credits.php", out)

    def test_check_passes_once_applied(self):
        self.run_main("credits", "--apply")
        code, _ = self.run_main("check")
        self.assertEqual(code, 0)


if __name__ == "__main__":
    unittest.main()
